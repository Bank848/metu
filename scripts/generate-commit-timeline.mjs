#!/usr/bin/env node
/**
 * Reads `git log` and writes apps/web/lib/admin/commit-timeline.ts —
 * the data the /admin/timeline page renders as a fishbone-style
 * timeline of every commit on main.
 *
 * Run after each commit batch (or just before deploy) so the page
 * stays in sync. Build is fast — < 100ms for ~250 commits.
 */
import { execSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "..");
const OUT = resolve(REPO_ROOT, "apps/web/lib/admin/commit-timeline.ts");

// ASCII unit separator + record separator survive Windows/Unix line
// endings cleanly without a fragile delimiter string.
const SEP = "\x1f";
const REC = "\x1e";

const FORMAT = ["%H", "%h", "%ad", "%an", "%s", "%P"].join(SEP);
const log = execSync(
  `git log main --no-merges --date=iso-strict --pretty=format:"${FORMAT}${REC}"`,
  { cwd: REPO_ROOT, encoding: "utf8", maxBuffer: 50 * 1024 * 1024 },
);

const commits = log
  .split(REC)
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line) => {
    const [sha, shortSha, dateIso, author, subject, parents] = line.split(SEP);
    return { sha, shortSha, dateIso, author, subject, parents };
  });

// Classify by Conventional Commits prefix. Same buckets the GitHub
// commit list uses so the colour coding feels familiar.
function classify(subject) {
  const m = subject.match(/^([a-z]+)(?:\(([^)]+)\))?(!)?:/i);
  if (!m) return { type: "other", scope: null };
  return { type: m[1].toLowerCase(), scope: m[2] ?? null };
}

const enriched = commits.map((c) => ({
  ...c,
  ...classify(c.subject),
}));

// TypeScript output — typed array literal so the page can map() it
// without runtime parse cost.
const tsLiteral = `// AUTO-GENERATED by scripts/generate-commit-timeline.mjs.
// Re-run after each commit batch:  node scripts/generate-commit-timeline.mjs
//
// Drives /admin/timeline. Edit the script, not this file.

export type CommitNode = {
  sha: string;
  shortSha: string;
  dateIso: string; // ISO 8601
  author: string;
  subject: string;
  type: string;    // feat | fix | docs | refactor | test | chore | …
  scope: string | null;
  parents: string;
};

export const COMMIT_TIMELINE: ReadonlyArray<CommitNode> = ${JSON.stringify(
  enriched,
  null,
  2,
)} as const;
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, tsLiteral, "utf8");
console.log(`Wrote ${enriched.length} commits → ${OUT}`);
